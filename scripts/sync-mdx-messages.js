// GT's React extractor scans TypeScript but does not parse Markdown nodes in
// imported MDX. Keep a generated msg() catalog so MDX remains the content
// source of truth while `gt translate` continues to emit the same GTJSON used
// by the live site and gt-rrweb.
import { createProcessor } from '@mdx-js/mdx'
import { hashMessage } from 'gt-i18n/internal'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const CONTENT_DIR = join(ROOT, 'src', 'content')
const GENERATED_DIR = join(ROOT, 'src', 'generated')
const OUTPUT = join(GENERATED_DIR, 'mdxMessages.ts')
const HASH_OUTPUT = join(GENERATED_DIR, 'translationHashes.ts')
const SOURCE_CATALOG = join(ROOT, 'src', '_gt', 'en.json')
const TRANSLATED_ATTRIBUTES = new Set([
  'description',
  'translatedLabel',
  'translatedName',
  'translatedWhen',
])
const COMPONENT_TRANSLATED_ATTRIBUTES = {
  ResumeEntry: new Set(['date', 'fact', 'gpa', 'title']),
  ResumeSkillCard: new Set(['title']),
  ResumeSkill: new Set(['label']),
}

function plainText(node, sourcePath) {
  if (node.type === 'text') return node.value
  if (!Array.isArray(node.children)) {
    throw new Error(`${sourcePath}: translated Markdown must contain plain text only`)
  }
  if (node.children.every((child) => child.type === 'text')) {
    return node.children.map((child) => child.value).join('')
  }
  // MDX can group adjacent JSX-only rows into a paragraph-shaped AST node,
  // even though it does not emit a <p>. Those components declare their own
  // translated attributes and are collected below.
  if (node.children.every((child) => child.type !== 'text' || !child.value.trim())) return null
  throw new Error(`${sourcePath}: translated Markdown must contain plain text only`)
}

function collectTextLeaves(node, messages) {
  if (node.type === 'text' || node.type === 'inlineCode') {
    const message = node.value?.trim()
    if (message) messages.add(message)
  }
  for (const child of node.children ?? []) collectTextLeaves(child, messages)
}

function collect(node, messages, sourcePath) {
  if (node.type === 'heading') {
    const message = plainText(node, sourcePath)
    if (message?.trim()) messages.add(message)
  }

  if (node.type === 'paragraph' || node.type === 'listItem') {
    collectTextLeaves(node, messages)
  }

  if (node.type === 'mdxJsxFlowElement' || node.type === 'mdxJsxTextElement') {
    const componentAttributes = COMPONENT_TRANSLATED_ATTRIBUTES[node.name]
    for (const attribute of node.attributes ?? []) {
      if (
        attribute.type !== 'mdxJsxAttribute' ||
        (!TRANSLATED_ATTRIBUTES.has(attribute.name) && !componentAttributes?.has(attribute.name))
      ) {
        continue
      }
      if (typeof attribute.value !== 'string') {
        throw new Error(
          `${sourcePath}: ${attribute.name} must be a quoted string so GT can extract it`,
        )
      }
      if (attribute.value.trim()) messages.add(attribute.value)
    }
  }

  for (const child of node.children ?? []) collect(child, messages, sourcePath)
}

const sourceFiles = (await readdir(CONTENT_DIR)).filter((name) => name.endsWith('.mdx')).sort()
const messages = new Set()
const processor = createProcessor({ format: 'mdx' })

for (const name of sourceFiles) {
  const sourcePath = join(CONTENT_DIR, name)
  const source = await readFile(sourcePath, 'utf8')
  collect(processor.parse(source), messages, relative(ROOT, sourcePath))
}

const output = `// Generated by scripts/sync-mdx-messages.js. Do not edit.\n// MDX is the source of truth; this file only makes its copy visible to the GT CLI.\nimport { msg } from 'gt-react'\n\nexport const mdxMessages = [\n${[
  ...messages,
]
  .map((message) => `  msg(${JSON.stringify(message)}),`)
  .join('\n')}\n]\n`

// The English GTJSON is also an exact source-message index. Generating the
// inverse map here lets the browser resolve hashes synchronously without
// shipping GT's SHA-256, ICU, formatting, and runtime-translation stacks.
const currentSourceCatalog = JSON.parse(await readFile(SOURCE_CATALOG, 'utf8'))
const sourceCatalog = Object.fromEntries(
  Object.entries({
    ...currentSourceCatalog,
    ...Object.fromEntries(
      [...messages].map((message) => [hashMessage(message, { $format: 'ICU' }), message]),
    ),
  }).sort(([a], [b]) => a.localeCompare(b)),
)
const sourceCatalogOutput = `${JSON.stringify(sourceCatalog, null, 2)}\n`
const hashesByMessage = Object.fromEntries(
  Object.entries(sourceCatalog)
    .filter((entry) => typeof entry[1] === 'string')
    .map(([hash, message]) => [message, hash])
    .sort(([a], [b]) => a.localeCompare(b)),
)
const hashOutput = `// Generated by scripts/sync-mdx-messages.js. Do not edit.\n// Maps extracted source strings to their stable GTJSON keys.\nexport const translationHashes: Readonly<Record<string, string>> = ${JSON.stringify(hashesByMessage, null, 2)}\n`

if (process.argv.includes('--check')) {
  const current = await readFile(OUTPUT, 'utf8').catch(() => '')
  if (current !== output) {
    console.error('MDX translation catalog is stale. Run: pnpm sync:mdx')
    process.exitCode = 1
  }
  const currentHashes = await readFile(HASH_OUTPUT, 'utf8').catch(() => '')
  if (currentHashes !== hashOutput) {
    console.error('Translation hash index is stale. Run: pnpm sync:mdx')
    process.exitCode = 1
  }
  const currentCatalog = await readFile(SOURCE_CATALOG, 'utf8').catch(() => '')
  if (currentCatalog !== sourceCatalogOutput) {
    console.error('English source catalog is stale. Run: pnpm sync:mdx')
    process.exitCode = 1
  }
} else {
  await mkdir(GENERATED_DIR, { recursive: true })
  await Promise.all([
    writeFile(OUTPUT, output),
    writeFile(HASH_OUTPUT, hashOutput),
    writeFile(SOURCE_CATALOG, sourceCatalogOutput),
  ])
}
