import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

// Repackage the compiler output without changing its geometry or resolution.
// Each response contains one text/font pair, including its outline fallback.
export async function splitGlyphfluxManifests(root = process.cwd()) {
  const config = JSON.parse(await readFile(resolve(root, 'glyphflux.config.json'), 'utf8'))
  const output = resolve(root, 'public/glyphflux')
  const byKey = {}
  const byLocale = {}
  const byText = {}
  const files = new Map()
  for (const locale of [config.defaultLocale, ...config.locales]) {
    const input = resolve(root, config.output.manifests.replaceAll('[locale]', locale))
    const manifest = JSON.parse(await readFile(input, 'utf8'))
    if (manifest.version !== 2) throw new Error(`Unsupported Glyphflux manifest: ${input}`)
    const urls = new Set()
    const keys = [
      ...new Set([...Object.keys(manifest.outlines), ...Object.keys(manifest.sdfMorphs)]),
    ]
    for (const key of keys.sort()) {
      const body = JSON.stringify({
        version: 2,
        outlines: key in manifest.outlines ? { [key]: manifest.outlines[key] } : {},
        sdfMorphs: key in manifest.sdfMorphs ? { [key]: manifest.sdfMorphs[key] } : {},
      })
      const hash = createHash('sha256').update(body).digest('hex')
      const filename = `${hash}.json`
      const url = `/glyphflux/${filename}`
      if (byKey[key] && byKey[key] !== url) throw new Error(`Conflicting Glyphflux pair: ${key}`)
      files.set(filename, body)
      byKey[key] = url
      urls.add(url)
      const text = JSON.parse(key)[0]
      ;(byText[text] ??= new Set()).add(url)
    }
    byLocale[locale] = [...urls]
  }

  await mkdir(output, { recursive: true })
  for (const [filename, body] of files) await writeFile(resolve(output, filename), body)
  const modulePath = resolve(root, 'src/generated/glyphfluxManifests.ts')
  await mkdir(resolve(root, 'src/generated'), { recursive: true })
  const textUrls = Object.fromEntries(
    Object.entries(byText).map(([text, urls]) => [text, [...urls]]),
  )
  await writeFile(
    modulePath,
    '// Generated by split-glyphflux-manifests.js. Do not edit.\n' +
      `export const glyphfluxManifestByKey: Readonly<Record<string, string>> = ${JSON.stringify(byKey, null, 2)}\n` +
      `export const glyphfluxManifestUrlsByLocale: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(byLocale, null, 2)}\n` +
      `export const glyphfluxManifestUrlsByText: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(textUrls, null, 2)}\n`,
  )
  // Only remove this generator's stale files and the superseded locale bundles.
  const legacy = new Set(
    [config.defaultLocale, ...config.locales].map((locale) => `${locale}.json`),
  )
  for (const filename of await readdir(output)) {
    if (legacy.has(filename) || (/^[a-f0-9]{64}\.json$/.test(filename) && !files.has(filename))) {
      await rm(resolve(output, filename))
    }
  }
  console.log(
    `Glyphflux: ${files.size} font-pair files; largest ${Math.max(...[...files.values()].map((body) => Buffer.byteLength(body)))} bytes.`,
  )
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await splitGlyphfluxManifests()
}
