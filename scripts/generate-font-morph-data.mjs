import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compileFontMorphManifest } from '../repos/font-morph/dist/index.mjs'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const gtConfig = JSON.parse(await readFile(resolve(projectRoot, 'gt.config.json'), 'utf8'))
const locales = [gtConfig.defaultLocale, ...gtConfig.locales]
const outlineFiles = {
  sans: ['public/fonts/ibm-plex-sans-400-outline.ttf', 'public/fonts/noto-sans-jp-400-outline.ttf'],
  serif: [
    'public/fonts/source-serif-4-600-outline.ttf',
    'public/fonts/noto-serif-jp-600-outline.ttf',
  ],
}

async function arrayBuffer(path) {
  const value = await readFile(resolve(projectRoot, path))
  return value.buffer.slice(value.byteOffset, value.byteOffset + value.byteLength)
}

const catalogs = Object.fromEntries(
  await Promise.all(
    locales.map(async (locale) => [
      locale,
      JSON.parse(await readFile(resolve(projectRoot, `src/_gt/${locale}.json`), 'utf8')),
    ]),
  ),
)
const resumeHash = Object.entries(catalogs.en).find(([, value]) => value === 'Resume')?.[0]
if (!resumeHash) throw new Error('Unable to find the translated Resume message')

const texts = Object.fromEntries(
  locales.map((locale) => {
    const value = catalogs[locale][resumeHash]
    if (typeof value !== 'string') throw new Error(`Resume must be a string in ${locale}.json`)
    return [locale, value]
  }),
)

// The destination heading is 23px on desktop and 20px on mobile. Optical
// size affects Source Serif's actual outline, so both viewport-independent
// templates must be compiled. The reverse transition reuses them by swapping
// source and target contours.
const requests = locales.flatMap((locale) =>
  [20, 23].map((opticalSize) => ({
    text: texts[locale],
    source: { role: 'sans', weight: 500, opticalSize: 0 },
    target: { role: 'serif', weight: 600, opticalSize },
  })),
)
const buffers = {
  sans: await Promise.all(outlineFiles.sans.map(arrayBuffer)),
  serif: await Promise.all(outlineFiles.serif.map(arrayBuffer)),
}
const manifest = await compileFontMorphManifest(buffers, requests)
const outputDirectory = resolve(projectRoot, 'public/font-morph')
await mkdir(outputDirectory, { recursive: true })

for (const locale of locales) {
  const text = texts[locale]
  const outlines = Object.fromEntries(
    Object.entries(manifest.outlines).filter(([key]) => JSON.parse(key)[0] === text),
  )
  await writeFile(
    resolve(outputDirectory, `${locale}.json`),
    `${JSON.stringify({ version: 1, outlines })}\n`,
  )
}

const generatedDirectory = resolve(projectRoot, 'src/generated')
await mkdir(generatedDirectory, { recursive: true })
const generatedSource = `// Generated by scripts/generate-font-morph-data.mjs. Do not edit.\nexport const fontMorphLocaleByText: Readonly<Record<string, string>> = ${JSON.stringify(
  Object.fromEntries(locales.map((locale) => [texts[locale], locale])),
  null,
  2,
)}\n`
await writeFile(resolve(generatedDirectory, 'fontMorphData.ts'), generatedSource)
